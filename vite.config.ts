import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import istanbul from "vite-plugin-istanbul";
// @ts-expect-error type error without @types/node package
import process from "node:process";
const host = process.env.TAURI_DEV_HOST;

// https://vite.dev/config/
export default defineConfig(() => ({
  plugins: [
    react(),

    // Line coverage for the Playwright suite (`make coverage-web`): every
    // module under `src/` is instrumented as the dev server serves it, and
    // `e2e/coverage.ts` collects the counters from the page. Off unless
    // `VITE_COVERAGE=true` (which `playwright.config.ts` sets under
    // `COVERAGE=1`), and never applied to a production build, so
    // `make check-no-fallback` still inspects the real bundle.
    istanbul({
      include: "src/**",
      exclude: [
        "node_modules",
        // The fake backend and its fault-injection hook exist for the tests
        // and never ship (see `src/api/backend.ts`): test code, not app code.
        "src/api/fallback.ts",
        // Generated by ts-rs from the Rust types; not written by hand.
        "src/bindings/**",
        "src/vite-env.d.ts",
      ],
      extension: [".ts", ".tsx"],
      requireEnv: true,
      checkProd: true,
    }),
  ],

  // Vite options tailored for Tauri development and only applied in `tauri dev` or `tauri build`
  //
  // 1. prevent Vite from obscuring rust errors
  clearScreen: false,
  // 2. tauri expects a fixed port, fail if that port is not available
  server: {
    port: 1420,
    strictPort: true,
    host: host || false,
    hmr: host
      ? {
          protocol: "ws",
          host,
          port: 1421,
        }
      : undefined,
    watch: {
      // 3. tell Vite to ignore watching `src-tauri` and the Cargo workspace's
      //    build output. `target/` runs to tens of gigabytes once the Rust
      //    side has been built, and watching it exhausts the inotify limit —
      //    the dev server then dies on startup with ENOSPC, taking the
      //    Playwright suite (which starts it) with it.
      ignored: ["**/src-tauri/**", "**/target/**"],
    },
  },
}));
